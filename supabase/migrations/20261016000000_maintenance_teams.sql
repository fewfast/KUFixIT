create extension if not exists pgcrypto with schema extensions;

create table if not exists public."Maintenance_Users" (
  id_team uuid primary key,
  created_at timestamptz not null default pg_catalog.now(),
  "teamName" text not null check (pg_catalog.btrim("teamName") <> ''),
  username text not null unique,
  password text not null
);

alter table public."Maintenance_Users" enable row level security;
revoke all on table public."Maintenance_Users" from public, anon, authenticated;
grant select, insert, update, delete on table public."Maintenance_Users"
  to service_role;

create or replace function public.create_maintenance_team(
  p_id_team uuid,
  p_team_name text,
  p_username text,
  p_password text,
  p_encrypted_password text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  team_name text := pg_catalog.btrim(p_team_name);
  table_name text := p_id_team::text;
begin
  if p_id_team is null
    or team_name is null
    or team_name = ''
    or pg_catalog.length(team_name) > 100
    or p_username is null
    or p_username !~ '^[A-Za-z0-9_]{3,64}$'
    or p_password is null
    or pg_catalog.octet_length(p_password) > 72
    or p_encrypted_password is null then
    raise exception 'Invalid maintenance team details.';
  end if;

  insert into public."Maintenance_Users" (
    id_team,
    "teamName",
    username,
    password
  )
  values (
    p_id_team,
    team_name,
    p_username,
    p_encrypted_password
  );

  execute pg_catalog.format(
    'create table public.%I (
      id bigint generated by default as identity primary key,
      created_at timestamptz not null default pg_catalog.now(),
      "teamName" text not null,
      username text not null unique,
      password text not null,
      start_time time[] not null default array[]::time[],
      end_time time[] not null default array[]::time[],
      status boolean not null default true,
      constraint %I check (
        pg_catalog.cardinality(start_time) = pg_catalog.cardinality(end_time)
      )
    )',
    table_name,
    'maintenance_team_time_pairs_check'
  );
  execute pg_catalog.format(
    'alter table public.%I enable row level security',
    table_name
  );
  execute pg_catalog.format(
    'revoke all on table public.%I from public, anon, authenticated',
    table_name
  );
  execute pg_catalog.format(
    'grant select, insert, update, delete on table public.%I to service_role',
    table_name
  );
  execute pg_catalog.format(
    'grant usage, select on sequence public.%I to service_role',
    table_name || '_id_seq'
  );
  execute pg_catalog.format(
    'insert into public.%I ("teamName", username, password)
     values ($1, $2, $3)',
    table_name
  ) using team_name, p_username, p_encrypted_password;

  insert into public."Systems_Users" ("Username", "Password", role)
  values (
    p_username,
    extensions.crypt(p_password, extensions.gen_salt('bf', 12)),
    'Technician'
  );

  perform pg_catalog.pg_notify('pgrst', 'reload schema');
end;
$$;

revoke all on function public.create_maintenance_team(
  uuid, text, text, text, text
) from public, anon, authenticated;
grant execute on function public.create_maintenance_team(
  uuid, text, text, text, text
) to service_role;

create or replace function public.rename_maintenance_team(
  p_id_team uuid,
  p_team_name text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  team_name text := pg_catalog.btrim(p_team_name);
  table_name text := p_id_team::text;
begin
  if p_id_team is null
    or team_name is null
    or team_name = ''
    or pg_catalog.length(team_name) > 100 then
    raise exception 'Invalid maintenance team name.';
  end if;

  update public."Maintenance_Users"
  set "teamName" = team_name
  where id_team = p_id_team;
  if not found then
    raise exception 'Maintenance team was not found.';
  end if;

  execute pg_catalog.format(
    'update public.%I set "teamName" = $1',
    table_name
  ) using team_name;
end;
$$;

revoke all on function public.rename_maintenance_team(uuid, text)
  from public, anon, authenticated;
grant execute on function public.rename_maintenance_team(uuid, text)
  to service_role;
