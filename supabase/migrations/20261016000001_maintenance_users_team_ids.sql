        when legacy_start_time is not null and legacy_end_time is not null
          then array[legacy_start_time::time]
        else array[]::time[]
      end,
      end_time = case
        when legacy_start_time is not null and legacy_end_time is not null
          then array[legacy_end_time::time]
        else array[]::time[]
      end;
  end if;
end;
$$;

with team_names as (
  select
    pg_catalog.lower(pg_catalog.btrim("teamName")) as normalized_name
  from public."Maintenance_Users"
  where id_team is null
  group by pg_catalog.lower(pg_catalog.btrim("teamName"))
), team_ids as (
  select normalized_name, extensions.gen_random_uuid() as id_team
  from team_names
)
update public."Maintenance_Users" as maintenance_user
set id_team = team_ids.id_team
from team_ids
where maintenance_user.id_team is null
  and pg_catalog.lower(pg_catalog.btrim(maintenance_user."teamName")) =
    team_ids.normalized_name;

