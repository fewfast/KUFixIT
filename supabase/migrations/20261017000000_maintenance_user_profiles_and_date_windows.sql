do $$
declare
  start_type oid;
  end_type oid;
begin
  select attribute.atttypid
    into start_type
  from pg_catalog.pg_attribute as attribute
  where attribute.attrelid =
      'public."Maintenance_Users"'::pg_catalog.regclass
    and attribute.attname = 'start_time'
    and not attribute.attisdropped;

  select attribute.atttypid
    into end_type
  from pg_catalog.pg_attribute as attribute
  where attribute.attrelid =
      'public."Maintenance_Users"'::pg_catalog.regclass
    and attribute.attname = 'end_time'
    and not attribute.attisdropped;

  if start_type = 'time[]'::pg_catalog.regtype then
    alter table public."Maintenance_Users"
      rename column start_time to legacy_time_of_day_start;
  elsif start_type is not null
    and start_type <> 'timestamptz[]'::pg_catalog.regtype then
    raise exception 'Unexpected Maintenance_Users.start_time type: %',
      start_type::pg_catalog.regtype;
  end if;

  if end_type = 'time[]'::pg_catalog.regtype then
    alter table public."Maintenance_Users"
      rename column end_time to legacy_time_of_day_end;
  elsif end_type is not null
    and end_type <> 'timestamptz[]'::pg_catalog.regtype then
    raise exception 'Unexpected Maintenance_Users.end_time type: %',
      end_type::pg_catalog.regtype;
  end if;
end;
$$;

