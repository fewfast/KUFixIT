create function public.create_maintenance_team(
  p_id_team uuid,
  p_technician_uid text,
  p_team_name text,
  p_username text,
  p_password text,
  p_encrypted_password text,
  p_comment text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  team_name text := pg_catalog.btrim(p_team_name);
  resolved_team_id uuid;
  resolved_technician_uid text := p_technician_uid;
begin
  if p_id_team is null
    or p_technician_uid is null
    or p_technician_uid !~ '^t_[0-9]{10}$'
    or team_name is null
    or team_name = ''
    or pg_catalog.length(team_name) > 100
    or p_username is null
    or p_username !~ '^[A-Za-z0-9_]{3,64}$'
    or p_password is null
    or pg_catalog.octet_length(p_password) > 72
    or p_encrypted_password is null
    or p_comment is null
    or pg_catalog.btrim(p_comment) = ''
    or pg_catalog.length(p_comment) > 1000 then
    raise exception 'Invalid maintenance technician details.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(pg_catalog.lower(team_name), 0)
  );
  perform pg_catalog.pg_advisory_xact_lock(192837465, 564738292);

  while exists (
    select 1
    from public."Maintenance_Users"
    where uid = resolved_technician_uid
  )
  loop
    resolved_technician_uid := 't_' || (
      1000000000 +
      pg_catalog.floor(pg_catalog.random() * 9000000000)::bigint
    )::text;
  end loop;

  select maintenance_user.id_team
    into resolved_team_id
  from public."Maintenance_Users" as maintenance_user
  where pg_catalog.lower(pg_catalog.btrim(maintenance_user."teamName")) =
    pg_catalog.lower(team_name)
  order by maintenance_user.created_at asc
  limit 1;

  if resolved_team_id is null then
    resolved_team_id := p_id_team;
  end if;

  insert into public."Maintenance_Users" (
    id_team,
    uid,
    "teamName",
    username,
    comment,
    password,
    start_time,
    end_time,
    status
  )
  values (
    resolved_team_id,
    resolved_technician_uid,
    team_name,
    p_username,
    p_comment,
    p_encrypted_password,
    array[]::timestamptz[],
    array[]::timestamptz[],
    true
  );

  insert into public."Systems_Users" ("Username", "Password", role)
  values (
    p_username,
    extensions.crypt(p_password, extensions.gen_salt('bf', 12)),
    'Technician'
  );

  perform public.create_technician_ticket_table(resolved_technician_uid);

  return pg_catalog.jsonb_build_object(
    'id_team',
    resolved_team_id,
    'uid',
    resolved_technician_uid
  );
end;
$$;

revoke all on function public.create_maintenance_team(
  uuid, text, text, text, text, text, text
) from public, anon, authenticated;
grant execute on function public.create_maintenance_team(
  uuid, text, text, text, text, text, text
) to service_role;

create or replace function public.authenticate_system_user(
  p_username text,
  p_password text
)
returns table (
  username text,
  role text,
  endtime timestamptz
)
language sql
security definer
set search_path = ''
as $$
  select
    staff_account."Username",
    staff_account.role,
    staff_account.endtime
  from public."Systems_Users" as staff_account
  where pg_catalog.lower(pg_catalog.btrim(staff_account."Username")) =
      pg_catalog.lower(pg_catalog.btrim(p_username))
    and staff_account."Password" =
      extensions.crypt(p_password, staff_account."Password")
    and (
      staff_account.endtime is null
      or staff_account.endtime > pg_catalog.now()
    )
    and (
      staff_account.role <> 'Technician'
      or exists (
        select 1
        from public."Maintenance_Users" as technician
        where pg_catalog.lower(pg_catalog.btrim(technician.username)) =
            pg_catalog.lower(pg_catalog.btrim(staff_account."Username"))
          and technician.status
          and pg_catalog.cardinality(technician.start_time) > 0
          and exists (
            select 1
            from pg_catalog.generate_subscripts(technician.start_time, 1)
              as schedule(index)
            where pg_catalog.timezone(
                    'Asia/Bangkok',
                    pg_catalog.now()
                  )::date between
                  pg_catalog.timezone(
                    'Asia/Bangkok',
                    technician.start_time[schedule.index]
                  )::date
                  and pg_catalog.timezone(
                    'Asia/Bangkok',
                    technician.end_time[schedule.index]
                  )::date
          )
      )
    )
  limit 1;
$$;

revoke all on function public.authenticate_system_user(text, text)
  from public, anon, authenticated;
grant execute on function public.authenticate_system_user(text, text)
  to service_role;

