do $$
declare
  id_sequence regclass;
  max_id bigint;
begin
  execute format(
    'select coalesce(max(id), 0) from %I.%I',
    'public',
    'Users'
  ) into max_id;

  id_sequence := pg_get_serial_sequence(
    format('%I.%I', 'public', 'Users'),
    'id'
  );

  if id_sequence is null then
    alter table public."Users"
      alter column id add generated by default as identity;
    id_sequence := pg_get_serial_sequence(
      format('%I.%I', 'public', 'Users'),
      'id'
    );
  end if;

  perform setval(id_sequence, max_id + 1, false);
  execute format('grant usage, select on sequence %s to service_role', id_sequence);
end;
$$;

alter table public."Users"
  alter column password drop not null;
